"""Split the exec_plain_id switch in emu/sh4exec.h into one small inline function per instruction
(emu/sh4sem.h), so recompiled code calls SEM_<OP>(c, op, pc) instead of inlining the whole switch."""
import re, os
src = open(os.path.join(os.path.dirname(__file__), "..", "emu", "sh4exec.h")).read()
body = src[src.index("switch (id) {") + len("switch (id) {"):]
body = body[:body.index("    default:")]
parts = re.split(r"(?m)^\s*((?:case OP_[A-Z0-9_]+:\s*)+)", body)
out = ["/* generated by tools/gen_sem.py from sh4exec.h - do not edit */", "#pragma once", '#include "sh4exec.h"']
n = 0
for i in range(1, len(parts), 2):
    labels = re.findall(r"OP_[A-Z0-9_]+", parts[i])
    code = parts[i + 1]
    code = re.sub(r"/\*\s*----.*?----\s*\*/", "", code).rstrip()
    k = code.rfind("break;")
    if k >= 0: code = code[:k] + code[k + 6:]
    for lab in labels:
        out.append(f"static inline void SEM_{lab}(Cpu *c, u16 op, u32 pc) {{ u32 t; (void)t; (void)pc; (void)op;\n    {code.strip()}\n}}")
        n += 1
out.append("static inline void SEM_OP_ILLEGAL(Cpu *c, u16 op, u32 pc) { sh4_illegal(c, pc, op); }")
open(os.path.join(os.path.dirname(__file__), "..", "emu", "sh4sem.h"), "w").write("\n".join(out) + "\n")
print("semantic functions:", n)
