# Generates emu/font8x16.h: 8x16 1-bpp glyphs (ASCII 32..126 + Spanish letters) from DejaVu Sans Mono Bold
# (Bitstream Vera / DejaVu license, free to embed). Extra glyphs: index 95.. = "áéíóúñÑ¿¡üÁÉÍÓÚ".
from PIL import Image, ImageDraw, ImageFont
import sys
f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 13)
chars = [chr(c) for c in range(32, 127)] + list("áéíóúñÑ¿¡üÁÉÍÓÚ")
out = ['/* generated by tools/mkfont.py from DejaVu Sans Mono Bold 13px (DejaVu/Bitstream Vera license) */',
       '#pragma once', '#include <stdint.h>', 'static const char *font_extra = "%s";' % "áéíóúñÑ¿¡üÁÉÍÓÚ",
       'static const uint8_t font8x16[%d][16] = {' % len(chars)]
for ch in chars:
    im = Image.new('L', (8, 16), 0); d = ImageDraw.Draw(im)
    d.text((0, 0), ch, font=f, fill=255)
    rows = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 110: b |= 0x80 >> x
        rows.append('0x%02x' % b)
    out.append('    { %s },' % ', '.join(rows))
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
