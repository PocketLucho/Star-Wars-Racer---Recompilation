"""SH-4 -> C static recompiler.

usage: recomp.py <image.bin> <base_hex> <catalog.json> <out.c> [--only-executed]

Each catalogued function becomes a C function `void f_XXXXXXXX(Cpu *c)`.
Non-branch instructions are emitted as exec_plain(c, <const op>, <const pc>), which the
C compiler specialises (sh4exec.h is always_inline + constant-folded), so the semantics
are exactly the interpreter's. The generator handles control flow:
basic blocks -> labels, delay slots, calls, returns, interrupt polling on back-edges/calls.
Anything it cannot place statically exits to the dispatcher with c->pc set.
"""
import sys, os, json, struct, argparse
sys.path.insert(0, os.path.dirname(__file__))
from sh4dec import decode, pcrel_target

ap = argparse.ArgumentParser()
ap.add_argument("image"); ap.add_argument("base"); ap.add_argument("catalog"); ap.add_argument("out")
ap.add_argument("--only-executed", action="store_true")
ap.add_argument("--max", type=int, default=0)
ap.add_argument("--split", type=int, default=1, help="write <out>_NN.c chunks + <out>_table.c")
A = ap.parse_args()

import re as _re
_opt = open(os.path.join(os.path.dirname(__file__), "..", "emu", "optable.h")).read()
_names = dict((int(v), k) for k, v in _re.findall(r"\b(OP_[A-Z0-9_]+) = (\d+),", _opt))
_pats = [(int(m, 16), int(v, 16), i) for m, v, i in _re.findall(r"\{0x([0-9a-f]+), 0x([0-9a-f]+), (OP_[A-Z0-9_]+)\}", _opt)]
def opid(op):
    for m, v, i in _pats:
        if op & m == v: return i
    return "OP_ILLEGAL"

img = open(A.image, "rb").read()
BASE = int(A.base, 16); END = BASE + len(img)
def r16(a):
    a &= 0x1fffffff
    return struct.unpack_from("<H", img, a - BASE)[0] if BASE <= a < END - 1 else None

cat = json.load(open(A.catalog))["functions"]
funcs = [f for f in cat if not f["suspect"] and (f["executed"] or not A.only_executed)]
if A.max: funcs = funcs[:A.max]
entries = {int(f["entry"], 16) for f in funcs}

def collect(entry):
    """Re-walk the function to get its instruction set and block starts."""
    insns, starts, q, seen = {}, {entry}, [entry], set()
    while q:
        a = q.pop()
        if a in seen: continue
        seen.add(a)
        while True:
            op = r16(a)
            if op is None: break
            ins = decode(op)
            if ins.illegal: insns[a] = ("illegal", op); break
            insns[a] = ("i", op)
            f = ins.flow; t = pcrel_target(ins, a)
            if f in ("bt", "bf"):
                starts.add(t); q.append(t); starts.add(a + 2); a += 2; continue
            if f in ("bts", "bfs"):
                insns[a + 2] = ("slot", r16(a + 2)); starts.add(t); q.append(t); starts.add(a + 4); a += 4; continue
            if f == "bra":
                insns[a + 2] = ("slot", r16(a + 2))
                if t not in entries or t == entry: starts.add(t); q.append(t)
                break
            if f in ("bsr", "jsr", "bsrf"):
                insns[a + 2] = ("slot", r16(a + 2)); starts.add(a + 4); a += 4; continue
            if f in ("rts", "rte", "jmp", "braf"):
                insns[a + 2] = ("slot", r16(a + 2)); break
            if f in ("trap", "sleep"):
                starts.add(a + 2); a += 2; continue
            a += 2
    return insns, starts

out = []
w = out.append
w('/* generated by tools/recomp.py - Star Wars Racer Arcade (Sega Hikaru), master SH-4 */')
w('#include "recomp_rt.h"')
for f in funcs:
    w(f'void f_{int(f["entry"],16):08x}(Cpu *c);')

def emit_slot(a, op):
    # delay-slot instruction: never a branch (illegal slot otherwise -> interpreter semantics)
    return f'SEM_{opid(op)}(c, 0x{op:04x}, 0x{a:08x}u);'

nfun = 0; ninsn = 0
for f in funcs:
    e = int(f["entry"], 16)
    insns, starts = collect(e)
    w(f'\n/* {f["name"]} */')
    w(f'void f_{e:08x}(Cpu *c) {{')
    w('  u32 t; int cond; (void)t; (void)cond;')
    w(f'  goto L_{e:08x};')
    addrs = sorted(insns)
    prev_fallthrough = False
    for a in addrs:
        kind, op = insns[a]
        if kind == "slot": continue
        if a in starts:
            if prev_fallthrough is False and a != e:
                pass
            w(f' L_{a:08x}:')
        ninsn += 1
        if kind == "illegal":
            w(f'  c->pc = 0x{a:08x}u; return;  /* illegal / data */'); prev_fallthrough = False; continue
        ins = decode(op); fl = ins.flow; tg = pcrel_target(ins, a)
        nxt = a + 2
        def jump(target, back=False):
            if target in insns and target in starts and insns[target][0] != "slot":
                poll = f'RC_POLL(c, 0x{target:08x}u); ' if target <= a else ''
                return f'{{ {poll}goto L_{target:08x}; }}'
            return f'{{ c->pc = 0x{target:08x}u; return; }}'
        if fl in ("bt", "bf"):
            cnd = "T_GET(c)" if fl == "bt" else "!T_GET(c)"
            w(f'  RC_CYC(c, 1); if ({cnd}) {jump(tg)}')
        elif fl in ("bts", "bfs"):
            cnd = "T_GET(c)" if fl == "bts" else "!T_GET(c)"
            w(f'  cond = {cnd}; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2); if (cond) {jump(tg)}')
            nxt = a + 4
        elif fl == "bra":
            w(f'  {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2);')
            if tg in entries and tg != e:
                w(f'  c->pc = 0x{tg:08x}u; RC_TAIL(c, 0x{tg:08x}u); return;')
            else:
                w(f'  {jump(tg)}')
            prev_fallthrough = False; continue
        elif fl == "bsr":
            w(f'  c->pr = 0x{a + 4:08x}u; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2);')
            if tg in entries:
                w(f'  RC_CALL_DIRECT(c, f_{tg:08x}, 0x{tg:08x}u, 0x{a + 4:08x}u);')
            else:
                w(f'  RC_CALL(c, 0x{tg:08x}u, 0x{a + 4:08x}u);')
            nxt = a + 4
        elif fl == "jsr":
            w(f'  t = c->r[{ins.n}]; c->pr = 0x{a + 4:08x}u; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2);')
            w(f'  RC_CALL(c, t, 0x{a + 4:08x}u);')
            nxt = a + 4
        elif fl == "bsrf":
            w(f'  t = 0x{a + 4:08x}u + c->r[{ins.n}]; c->pr = 0x{a + 4:08x}u; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2);')
            w(f'  RC_CALL(c, t, 0x{a + 4:08x}u);')
            nxt = a + 4
        elif fl == "rts":
            w(f'  t = c->pr; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2); c->pc = t; return;')
            prev_fallthrough = False; continue
        elif fl == "jmp":
            w(f'  t = c->r[{ins.n}]; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2); c->pc = t; return;')
            prev_fallthrough = False; continue
        elif fl == "braf":
            w(f'  t = 0x{a + 4:08x}u + c->r[{ins.n}]; {emit_slot(a + 2, insns[a + 2][1])} RC_CYC(c, 2); c->pc = t; return;')
            prev_fallthrough = False; continue
        elif fl == "rte":
            w(f'  c->pc = 0x{a:08x}u; RC_INTERP_ONE(c); return;')
            prev_fallthrough = False; continue
        elif fl in ("trap", "sleep"):
            w(f'  c->pc = 0x{a:08x}u; RC_INTERP_ONE(c); if (c->pc != 0x{a + 2:08x}u) return;')
        else:
            w(f'  SEM_{opid(op)}(c, 0x{op:04x}, 0x{a:08x}u); RC_CYC(c, 1);')
        prev_fallthrough = True
        # fall through into an address not in this function's instruction set
        if nxt not in insns:
            w(f'  c->pc = 0x{nxt:08x}u; return;')
            prev_fallthrough = False
    w('}')
    nfun += 1

if A.split > 1:
    # out holds: 2 header lines, decls, then per-function bodies. Re-split on function markers.
    text = "\n".join(out)
    head_end = text.index("\n/* ", text.index("void f_"))
    header = text[:head_end]
    bodies = text[head_end:].split("\n/* ")[1:]
    base = A.out[:-2] if A.out.endswith(".c") else A.out
    per = (len(bodies) + A.split - 1) // A.split
    for k in range(A.split):
        chunk = bodies[k * per:(k + 1) * per]
        open(f"{base}_{k:02d}.c", "w").write(header + "\n" + "".join("\n/* " + b for b in chunk) + "\n")
    out = [header]
    w = out.append
    A.out = f"{base}_table.c"
# function table
w('\nconst RcEntry rc_table[] = {')
for f in sorted(funcs, key=lambda f: int(f["entry"], 16)):
    e = int(f["entry"], 16); w(f'  {{0x{e:08x}u, f_{e:08x}}},')
w('};')
w(f'const int rc_table_n = {nfun};')
open(A.out, "w").write("\n".join(out) + "\n")
print(f"recompiled {nfun} functions, {ninsn} instructions -> {A.out}")
