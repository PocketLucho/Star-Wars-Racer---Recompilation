"""Generate emu/optable.h from the shared Python decoder table (single source of truth)."""
import sys, os, re
sys.path.insert(0, os.path.dirname(__file__))
import sh4dec

def cname(mn):
    s = mn.replace("@-", "predec_").replace("@+", "postinc_").replace("+", "_inc").replace("@", "at_")
    s = s.replace("#", "imm_").replace("/", "_").replace(".", "_").replace(",", "_").replace(" ", "_")
    s = s.replace("(", "").replace(")", "")
    s = re.sub("_+", "_", s).strip("_")
    return "OP_" + s.upper()

seen = []
for mask, val, mn, pat, flow, delay in sh4dec.T:
    if mn not in seen: seen.append(mn)

out = ["/* generated by tools/gen_optable.py - do not edit */", "#pragma once", "enum {", "  OP_ILLEGAL = 0,"]
for i, mn in enumerate(seen, 1):
    out.append(f"  {cname(mn)} = {i}, /* {mn} */")
out.append(f"  OP_COUNT = {len(seen)+1}")
out.append("};")
out.append("static const struct { unsigned short mask, val; unsigned short id; } sh4_patterns[] = {")
for mask, val, mn, pat, flow, delay in sh4dec.T:
    out.append(f"  {{0x{mask:04x}, 0x{val:04x}, {cname(mn)}}},")
out.append("};")
out.append("static const char *sh4_opnames[] = { \"illegal\",")
for mn in seen: out.append(f"  \"{mn}\",")
out.append("};")
os.makedirs(sys.argv[1], exist_ok=True)
open(os.path.join(sys.argv[1], "optable.h"), "w").write("\n".join(out) + "\n")
print(len(seen), "opcodes")
for mn in seen: print(cname(mn))
