"""Writes tools/blockgen_ops.h (opcode patterns, names and which have a SEM_ function) for blockgen.c,
from emu/optable.h and emu/sh4sem.h. No game data involved."""
import re, os
H = os.path.dirname(os.path.abspath(__file__)); E = os.path.join(H, "..", "emu")
pats = re.findall(r"\{0x([0-9a-f]+), 0x([0-9a-f]+), (OP_[A-Z0-9_]+)\}", open(os.path.join(E, "optable.h")).read())
sem = set(re.findall(r"static inline void SEM_(OP_[A-Z0-9_]+)\(", open(os.path.join(E, "sh4sem.h")).read()))
with open(os.path.join(H, "blockgen_ops.h"), "w") as f:
    f.write("/* generated by tools/gen_blockgen_ops.py - do not edit */\n")
    f.write("static const struct { unsigned short mask, val; const char *name; int has_sem; } OPS[] = {\n")
    for m, v, n in pats: f.write('  {0x%s, 0x%s, "%s", %d},\n' % (m, v, n, n in sem))
    f.write("};\n")
